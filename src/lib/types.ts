export type Member = { id: string; name: string; folder: string };
export type Photo = {
  duplicate?: boolean;
  revision?: string;
  id: string;
  name: string;
  folder: string;
  owner: string;
  width: number;
  height: number;
  bytes: number;
  modifiedAt: string;
  takenAt?: string;
  previewStatus: 'ready' | 'pending' | 'unavailable';
};
export type PhotoList = {
  searchTruncated?: boolean;
  photos: Photo[];
  members: Member[];
  folders: { folder: string; name: string; count: number }[];
  total: number;
  offset: number;
  hasMore: boolean;
  previewService: 'ready' | 'unconfigured' | 'unavailable';
};

export type PhotoMetadata = {
  description?: string;
  takenAt?: string;
  timeZone?: string;
  make?: string;
  model?: string;
  lensModel?: string;
  fNumber?: number;
  focalLength?: number;
  iso?: number;
  exposureTime?: string;
  latitude?: number;
  longitude?: number;
  city?: string;
  state?: string;
  country?: string;
  rating?: number;
  width?: number;
  height?: number;
  mimeType?: string;
  people: { id: string; name: string }[];
  tags: string[];
};
export type PhotoInformation = { state: 'ready' | 'pending' | 'unconfigured' | 'unavailable'; metadata?: PhotoMetadata };
